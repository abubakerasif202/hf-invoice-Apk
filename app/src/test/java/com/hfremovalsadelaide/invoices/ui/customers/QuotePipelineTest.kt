package com.hfremovalsadelaide.invoices.ui.customers

import org.json.JSONArray
import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [35])
class QuotePipelineTest {

    @Test
    fun `stages use the server keys the backend accepts, with readable labels`() {
        assertEquals(
            listOf("new_enquiry", "quote_prepared", "quote_sent", "accepted", "booking_confirmed", "job_completed", "invoiced", "paid"),
            QuoteStage.pipeline.map { it.key }
        )
        assertEquals("New Enquiry", QuoteStage.NEW_ENQUIRY.label)
        assertEquals("Booking Confirmed", QuoteStage.BOOKING_CONFIRMED.label)
    }

    @Test
    fun `a new quote is created at the new_enquiry key, not its label`() {
        assertEquals("new_enquiry", QuoteStage.INITIAL.key)
    }

    @Test
    fun `the next stage is found from the server key the API returns`() {
        assertEquals(QuoteStage.QUOTE_PREPARED, QuoteStage.next("new_enquiry"))
        assertEquals(QuoteStage.PAID, QuoteStage.next("invoiced"))
        assertNull("paid is the end of the pipeline", QuoteStage.next("paid"))
        assertNull("declined and archived quotes are not advanced", QuoteStage.next("declined"))
        assertNull(QuoteStage.next("New Enquiry"))
    }

    @Test
    fun `labels cover every server stage, including ones outside the pipeline`() {
        assertEquals("Quote Sent", QuoteStage.labelFor("quote_sent"))
        assertEquals("Declined", QuoteStage.labelFor("declined"))
        assertEquals("Archived", QuoteStage.labelFor("archived"))
        assertEquals("unknown_stage", QuoteStage.labelFor("unknown_stage"))
    }

    /** quote_api_contract.json is generated by the backend (tests/quote-contract.test.ts) from what its API accepts. */
    private fun contract(): JSONObject = JSONObject(
        requireNotNull(javaClass.classLoader?.getResourceAsStream("quote_api_contract.json")).bufferedReader().readText()
    )

    private fun JSONArray.strings() = List(length()) { getString(it) }

    @Test
    fun `every stage the app knows is exactly the set the backend accepts`() {
        assertEquals(contract().getJSONArray("quoteStages").strings(), QuoteStage.entries.map { it.key })
    }

    @Test
    fun `every template kind the app sends is exactly the set the backend accepts`() {
        assertEquals(contract().getJSONArray("templateKinds").strings(), QUOTE_TEMPLATE_KINDS.map { it.first })
    }

    @Test
    fun `template kinds match the backend's accepted kinds`() {
        assertEquals(
            listOf("quote", "booking_confirmation", "reminder", "post_move_followup", "payment_request"),
            QUOTE_TEMPLATE_KINDS.map { it.first }
        )
    }
}
